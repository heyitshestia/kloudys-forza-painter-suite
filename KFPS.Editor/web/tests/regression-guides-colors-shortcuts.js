async (page,options={}) => {
  const h=require(path.join(__dirname,'dense-human-fixture.cjs'));
  let count=Number(options.layers || 2);
  const check = (value, message) => { if (!value) throw new Error(message); };
  const checks = [];
  const handmade=options.project ? await require(path.join(__dirname,'handmade-project-fixture.cjs')).setup(page,output,options) : null;
  if(handmade) {
    count=handmade.layers;
    const id=await page.evaluate(()=>vinylObjects()[1].kloudy.editor_id);
    await require(path.join(__dirname,'handmade-project-fixture.cjs')).selectId(page,id);
    await page.locator('#layers .layerRow.active .layerLock').click();
    await require(path.join(__dirname,'handmade-project-fixture.cjs')).saveAs(page,'Guide controls audit');
  } else await page.evaluate(async count => {
    await loadPayload({ shapes: Array.from({length:count},(_,i) => ({ type: 1048677 + i%2, color: [40, 150, 200, 255], data: i<2?[i * 300, 0, .5, .5, 0, 0, 0]:[-270+i%60*9,185-Math.floor(i/60)*7.5,.07,.07,0,0,0], editor_locked: i===1 })) });
    currentProjectName = 'Guide controls audit';
    await saveProject();
  },count);
  if(options.reference && !handmade) {
    await h.fileInput(page,'#overlayInput',options.reference);
    await page.waitForFunction(()=>!!editorReference.image);
    await page.locator('#saveProject').click();await page.waitForFunction(()=>!projectSaveInProgress&&!documentDirty);
  }
  await page.locator('#fitView').click();
  const initial=await h.scene(page);
  if(initial.visible<count*.8)throw Error('Guide/control fixture not densely visible');
  await page.locator('[data-tool-mode="guides"]').click();
  await page.locator('#gridEnabled').check();
  check(await page.evaluate(() => documentDirty), 'Changing saved grid settings must mark the project unsaved');
  await page.locator('#gridSize').fill('0');
  await page.locator('#gridSize').press('Tab');
  check(await page.evaluate(() => guideState.gridSize === 5), 'Grid lower boundary is not clamped');
  await page.locator('#gridSize').fill('99999');
  await page.locator('#gridSize').press('Tab');
  check(await page.evaluate(() => guideState.gridSize === 500), 'Grid upper boundary is not clamped');
  await page.locator('#gridSize').fill('50');
  await page.locator('#gridSize').press('Tab');
  await page.locator('#guideConstraint').selectOption('horizontal');
  await page.locator('#snapGuideAnchor').check();
  await page.locator('#snapGuideEnd').check();
  const bounds = await page.locator('.upper-canvas').boundingBox();
  await page.mouse.move(bounds.x + bounds.width * .2, bounds.y + bounds.height * .3);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * .55, bounds.y + bounds.height * .45, { steps: 8 });
  await page.mouse.up();
  check(await page.evaluate(count => guideState.guides.length === 1 && guideState.guides[0].y1 === guideState.guides[0].y2
    && guideState.guides[0].x1 % 50 === 0 && guideState.guides[0].x2 % 50 === 0 && vinylObjects().length === count,count), 'Pointer-created constrained/snapped guide is incorrect');
  await page.evaluate(async () => { await undo(); if (guideState.guides.length) throw new Error('Guide undo failed'); await redo(); if (guideState.guides.length !== 1) throw new Error('Guide redo failed'); selectedGuideId = guideState.guides[0].id; });
  await page.locator('#deleteGuide').click();
  check(await page.evaluate(() => !guideState.guides.length), 'Delete Guide failed');
  await page.locator('#deleteGuide').click();
  await page.evaluate(() => undo());
  await page.locator('#guidesVisible').uncheck();
  await page.locator('#snapGuides').uncheck();
  await page.locator('#snapGrid').uncheck();
  await page.locator('#snapCtrlOnly').uncheck();
  await page.locator('#clearGuides').click();
  check(await page.evaluate(() => !guideState.guides.length && guideState.gridEnabled), 'Clear Guides changed grid preferences');
  await page.evaluate(() => undo());
  const guides = await page.evaluate(async () => { await saveProject(); return JSON.stringify(savedGuideState()); });
  await page.evaluate(async () => {
    const { payload, receipt } = await (await fetch(`${PROJECT_FILE_API}?id=Guide%20controls%20audit.fabric-project.json`)).json();
    await loadProjectPayload(payload, 'Guide controls audit', { receipt });
  });
  check(await page.evaluate(expected => JSON.stringify(savedGuideState()) === expected, guides), 'Guide project reopen differs');
  checks.push('guide controls, pointer drawing, numeric boundaries, delete/clear, undo/redo and project reopen');

  await page.locator('[data-tool-mode="select"]').click();
  await page.locator('#selectAllLayers').click();
  const locked = await page.evaluate(() => JSON.stringify(snapshotShapes()[1]));
  await page.locator('#quickColorSwatch').click();
  await page.locator('#dialogColorPicker').evaluate(input => { input.value = '#12ab34'; input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); });
  await page.locator('#favoriteColorGrid button').nth(0).click();
  await page.locator('#saveFavoriteColor').click();
  check(await page.evaluate(() => JSON.stringify(favoriteColors[0]) === JSON.stringify([18, 171, 52, 255])), 'Palette Save Color is incorrect');
  check(await page.evaluate(expected => JSON.stringify(snapshotShapes()[1]) === expected, locked), 'Color picker changed a locked layer');
  await page.locator('#removeFavoriteColor').click();
  await page.locator('#removeFavoriteColor').click();
  check(await page.evaluate(() => favoriteColors[0] === null), 'Palette clear-empty is not safe');
  await page.locator('#saveFavoriteColor').click();
  await page.locator('#clearFavoriteColors').click();
  check(await page.evaluate(() => favoriteColors.every(color => color === null)), 'Clear palette left entries');
  await page.locator('#saveFavoriteColor').click();
  await page.locator('#closeColorDialog').click();
  if(handmade)await require(path.join(__dirname,'handmade-project-fixture.cjs')).selectId(page,await page.evaluate(()=>vinylObjects()[0].kloudy.editor_id));
  else await page.evaluate(() => selectObjects([vinylObjects()[0]], 'transparent palette test'));
  await page.locator('#opacitySlider').evaluate(input => { input.value = '0'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.locator('#quickColorSwatch').click();
  await page.locator('#dialogColorPicker').evaluate(input => { input.value = '#345678'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.locator('#closeColorDialog').click();
  check(await page.evaluate(() => JSON.stringify(snapshotShapes()[0].color) === JSON.stringify([52, 86, 120, 0])), 'Palette close lost a pending preview or zero alpha');
  checks.push('palette save/clear/reuse, locked layer, alpha zero and pending-preview commit');

  await page.locator('#shortcutsBtn').click();
  const binding = page.locator('[data-shortcut-action="shapeLibrary"]');
  const old = await binding.inputValue();
  await binding.click();
  await binding.press('v');
  check(await page.evaluate(old => shortcutFor('shapeLibrary') === old && shortcutFor('selectTool') === 'V', old), 'Duplicate shortcut disabled an existing binding');
  await binding.click();
  await binding.press('Space');
  check(await page.evaluate(() => shortcutFor('shapeLibrary') === 'Space'), 'Space shortcut was not captured');
  await page.locator('#closeShortcuts').click();
  await page.locator('[data-tool-mode="select"]').click();
  await page.keyboard.press('Space');
  check(await page.evaluate(() => activeToolMode === 'shapeLibrary'), 'Space shortcut did not activate its tool');
  await page.locator('#shortcutsBtn').click();
  await page.locator('#resetShortcuts').click();
  await binding.click();
  await binding.dispatchEvent('keydown', { key: 'Process', isComposing: true, keyCode: 229 });
  check(await page.evaluate(old => shortcutFor('shapeLibrary') === old, old), 'IME input overwrote a shortcut');
  await binding.press('Escape');
  await binding.click();
  await binding.press('Control+Alt+L');
  check(await page.evaluate(() => shortcutFor('shapeLibrary') === 'Ctrl+Alt+L'), 'Shortcut capture failed');
  await page.locator('#closeShortcuts').click();
  await page.locator('[data-tool-mode="select"]').click();
  await page.keyboard.press('Control+Alt+L');
  check(await page.evaluate(() => activeToolMode === 'shapeLibrary'), 'Custom shortcut did not activate its tool');
  await page.evaluate(async () => {
    await saveProject(); await KfpsEditorPreferences.flush();
    if (documentDirty) throw Error('Project save did not complete before reload');
  });
  await page.reload();
  await page.waitForFunction(() => window.KfpsDesktop?.ready);
  check(await page.evaluate(() => shortcutFor('shapeLibrary') === 'Ctrl+Alt+L' && favoriteColors[0]?.[0] === 18), 'Shortcut or palette failed to persist');
  await page.locator('#shortcutsBtn').click();
  await page.locator('#resetShortcuts').click();
  check(await page.evaluate(() => JSON.stringify(shortcuts) === JSON.stringify(DEFAULT_SHORTCUTS)), 'Shortcut reset failed');
  await page.locator('#closeShortcuts').click();
  checks.push('shortcut IME rejection, capture/cancel, actual key action, persistence and reset');
  return checks;
}
